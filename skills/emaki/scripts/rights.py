def collect(root, P=None):
    """{path: {"kind", "abs", "index", "why"}} of every external file the film may use. Paths
    inside the project are relative ("assets/music.mp3"); system fonts keep their absolute path."""
    root = os.path.abspath(root)
    files = {}
    for sub in ("assets", "fonts"):
        for p in glob.glob(os.path.join(root, sub, "**", "*"), recursive=True):
            rp = _rel(root, p)
            if os.path.isfile(p) and not IGNORE.search(rp) and not LICENSE_FILE.search(os.path.basename(p)):
                files[rp] = {"kind": _kind(p), "abs": p, "index": 0, "why": f"in {sub}/"}
    if P is None:
        return files
    for lay in _walk_layers(P):
        p = getattr(lay, "path", None)
        if isinstance(p, str) and os.path.isfile(p):
            files.setdefault(_rel(root, p), {"kind": _kind(p), "abs": os.path.abspath(p), "index": 0,
                                              "why": f"drawn by layer '{getattr(lay, 'name', '?')}'"})
    try:
        snd = P.design.sound or {}
    except Exception:
        snd = {}
    if isinstance(snd, dict):
        for k in ("track", "voice"):
            v = snd.get(k)
            if isinstance(v, str) and v and os.path.isfile(os.path.join(root, v)):
                pa = os.path.join(root, v)
                files.setdefault(_rel(root, pa), {"kind": "audio", "abs": pa, "index": 0, "why": f"design.yaml sound.{k}"})
    try:
        from engine import fonts as F
        for (fp, idx) in list(F._faces):
            files.setdefault(_rel(root, fp), {"kind": "font", "abs": os.path.abspath(fp), "index": idx,
                                               "why": "used by the text"})
    except Exception:
        pass
    return files


def load_ledger(root):
    p = os.path.join(root, "licenses", "assets.yaml")
    if not os.path.exists(p):
        return None, []
    import yaml
    d = yaml.safe_load(open(p, encoding="utf-8")) or {}
    return d, [i for i in (d.get("items") or []) if isinstance(i, dict)]


def _match(path, pat):
    pat = pat.strip()
    return fnmatch.fnmatchcase(path, pat) or (os.path.isabs(path) and fnmatch.fnmatchcase(os.path.basename(path), pat))


def evaluate(root, it):
    """(status, blocked reasons, gaps) of one ledger row. status: ok | gap | blocked."""
    lic = str(it.get("license") or "unknown").strip().lower()
    kind = str(it.get("kind") or "").strip().lower()
    st = str(it.get("status") or "").strip().lower()
    src = str(it.get("source") or "").strip()
    proofs = _as_list(it.get("proof"))
    blocked, gaps = [], []
    if st == "blocked":
        blocked.append(str(it.get("note") or "marked blocked in the ledger"))
    elif lic not in LICENSES:
        blocked.append("license unknown" if lic in ("", "unknown", "none", "?") else
                       f"license '{lic}' is not one the skill knows (use other + license_url)")
    if lic in STOCK:
        doms = LICENSES[lic]["domains"]
        if not src:
            gaps.append("add the link to the page it was downloaded from")
        elif not any(_host(src) == d or _host(src).endswith("." + d) for d in doms):
            blocked.append(f"the source {_host(src) or src} is not {lic}: the {LICENSES[lic]['name']} covers only files from {lic}")
        if lic == "pixabay" and kind in ("music", "sfx", "audio", "voice") and not proofs:
            gaps.append("save a screenshot or PDF of the Pixabay page in licenses/; if it shows the shield icon "
                        "(Content ID), also the License Certificate from the Download menu (needs a login)")
        if str(it.get("content_id", "")).strip().lower() in ("yes", "true") and not any("certif" in p.lower() for p in proofs):
            gaps.append("the track is registered in Content ID: save its License Certificate in licenses/, expect claims")
    if lic in NEEDS_PROOF and not proofs:
        gaps.append(NEEDS_PROOF[lic])
    if lic == "other":
        if not it.get("license_url"):
            gaps.append("add license_url")
        if st != "ok":
            gaps.append("review the license, then set status: ok")
    if lic == "own" and not (it.get("note") or it.get("author")):
        gaps.append("note who made it and how (author or note)")
    for p in proofs:
        if not os.path.exists(os.path.join(root, "licenses", p)):
            gaps.append(f"proof file licenses/{p} not found")
    if st == "ok" and not blocked:            # reviewed by the user: only a missing proof file stays
        gaps = [g for g in gaps if g.startswith("proof file")]
    return ("blocked" if blocked else "gap" if gaps else "ok"), blocked, gaps


def audit(root, P=None):
    root = os.path.abspath(root)
    files = collect(root, P)
    meta, items = load_ledger(root)
    rows, covered = [], set()
    for it in items:
        pats = _as_list(it.get("files"))
        matched = sorted(f for f in files if any(_match(f, p) for p in pats))
        covered.update(matched)
        status, blocked, gaps = evaluate(root, it)
        refs = [f for f in matched if f.startswith("refs/")]
        if refs:
            blocked.append(f"reference material in the film ({', '.join(refs[:3])}): refs/ never reaches the final")
            status = "blocked"
        rows.append({"item": it, "files": matched, "status": status, "blocked": blocked, "gaps": gaps})
    auto, missing = {}, []
    for f, info in sorted(files.items()):
        if f in covered:
            continue
        if info["kind"] == "font":
            lic, fam, url = font_license(info["abs"], info.get("index", 0))
            if lic:
                a = auto.setdefault((fam, lic), {"family": fam, "license": lic, "url": url, "files": []})
                a["files"].append(f)
                continue
        missing.append(f)
    return {"root": root, "files": files, "rows": rows, "auto": list(auto.values()), "missing": missing,
            "ledger": meta is not None, "meta": meta or {}}


def group_paths(paths, limit=3):
    """['assets/lots/ (86 files)', 'assets/music.mp3'] for messages."""
    by = {}
    for p in paths:
        by.setdefault(os.path.dirname(p) or ".", []).append(p)
    out = []
    for d, ps in sorted(by.items()):
        out.extend(ps if len(ps) <= limit else [f"{d}/ ({len(ps)} files)"])
    return out


def label(row):
    it = row["item"]
    t = str(it.get("title") or "").strip()
    a = str(it.get("author") or "").strip()
    if t:
        return f"{t}{' by ' + a if a else ''}"
    return ", ".join(_as_list(it.get("files"))[:3]) or "ledger row"


def summary(A):
    n = {"ok": 0, "gap": 0, "blocked": 0}
    for r in A["rows"]:
        n[r["status"]] += 1
    return n



def ensure(root):
    d = os.path.join(root, "licenses")
    os.makedirs(d, exist_ok=True)
    p = os.path.join(d, "assets.yaml")
    if not os.path.exists(p):
        shutil.copy(TEMPLATE, p)
    return p


def add_stubs(root, missing, files):
    """Append one stub row per directory group of uncovered files (explicit names up to 5)."""
    if not missing:
        return 0
    p = ensure(root)
    txt = open(p, encoding="utf-8").read()
    txt = re.sub(r"(?m)^items:\s*\[\s*\]\s*$", "items:", txt)
    if not re.search(r"(?m)^items:\s*$", txt):
        txt = txt.rstrip() + "\n\nitems:\n"
    by = {}
    for f in missing:
        by.setdefault((os.path.dirname(f), files[f]["kind"]), []).append(f)
    today = datetime.date.today().isoformat()
    blocks = []
    for (d, kind), fs in sorted(by.items()):
        if os.path.isabs(d):                  # system fonts: matched by file name
            pats = sorted(os.path.basename(f) for f in fs)
        elif len(fs) <= 5:
            pats = fs
        else:
            exts = sorted({os.path.splitext(f)[1] for f in fs})
            pats = [f"{d}/*{e}" for e in exts]
        blocks.append(
            f"  - files: [{', '.join(repr(x).replace(chr(39), chr(34)) for x in pats)}]   # added by mv.py licenses {today}, {len(fs)} file(s): fill in\n"
            f"    kind: {'music' if kind == 'audio' else kind}\n"
            f"    title: \"\"\n"
            f"    author: \"\"\n"
            f"    source: \"\"          # the page it came from\n"
            f"    license: unknown    # pixabay | unsplash | ofl | apache | client | permission | own | google-tts | other\n"
            f"    obtained: \"\"        # YYYY-MM-DD\n"
            f"    proof: []           # files in licenses/: certificate, page screenshot, client's email\n"
            f"    note: \"\"\n")
    open(p, "w", encoding="utf-8").write(txt.rstrip() + "\n" + "".join(blocks))
    return len(blocks)


def add_tts_row(root, voice):
    """A ledger row for the generated voice (mv.py tts), unless a row already covers
    assets/voice.wav. Returns True when a row was added."""
    p = ensure(root)
    _meta, items = load_ledger(root)
    if any(_match("assets/voice.wav", pat) for it in items for pat in _as_list(it.get("files"))):
        return False
    txt = open(p, encoding="utf-8").read()
    txt = re.sub(r"(?m)^items:\s*\[\s*\]\s*$", "items:", txt)
    if not re.search(r"(?m)^items:\s*$", txt):
        txt = txt.rstrip() + "\n\nitems:\n"
    today = datetime.date.today().isoformat()
    row = (f"  - files: [\"assets/voice.wav\"]   # added by mv.py tts {today}\n"
           f"    kind: voice\n"
           f"    title: \"Voice-over, {voice}\"\n"
           f"    author: \"Google Cloud Text-to-Speech, library voice {voice}; the script is ours (data/voice_phrases.json)\"\n"
           f"    source: https://cloud.google.com/text-to-speech/docs/chirp3-hd\n"
           f"    license: google-tts\n"
           f"    license_url: https://cloud.google.com/terms/service-terms\n"
           f"    obtained: \"{today}\"\n"
           f"    proof: []\n"
           f"    terms: [google-tts-terms-summary_2026-10-19.md]\n"
           f"    note: \"Generated voice, not a recording of a person. A library voice: other companies can use the same "
           f"voice, it is not exclusive to the brand. Google gives no indemnity for it.\"\n")
    open(p, "w", encoding="utf-8").write(txt.rstrip() + "\n" + row)
    return True


def _voice_copy(root):
    """Voice-over lines we wrote (not verbatim from the brief), from data/voice_phrases.json."""
    p = os.path.join(root, "data", "voice_phrases.json")
    if not os.path.exists(p):
        return []
    import json
    try:
        rows = (json.load(open(p, encoding="utf-8")) or {}).get("phrases") or []
    except Exception:
        return []
    return [r["text"] for r in rows if not r.get("from_brief")]


def copy_snapshots(root, A):
    used = {str(r["item"].get("license", "")).lower() for r in A["rows"]}
    out = []
    for lic in used:
        for name in LICENSES.get(lic, {}).get("snapshots", ()):
            src = os.path.join(SNAPSHOTS, name)
            dst = os.path.join(root, "licenses", name)
            if os.path.exists(src) and not os.path.exists(dst):
                shutil.copy(src, dst)
                out.append(name)
    return out


def _invented_copy(P):
    if P is None:
        return []
    try:
        from engine.layers.text import Text
    except Exception:
        return []
    seen, out = set(), []
    for lay in _walk_layers(P):
        if isinstance(lay, Text) and getattr(lay, "src", "brief") == "invented" and getattr(lay, "text_role", "copy") == "copy":
            t = " ".join(str(getattr(lay, "plain", "")).split())
            if t and t not in seen:
                seen.add(t)
                out.append(t)
    return out


def _brief(root):
    p = os.path.join(root, "brief.yaml")
    if not os.path.exists(p):
        return {}
    import yaml
    return yaml.safe_load(open(p, encoding="utf-8")) or {}


def write_readme(root, P, A):
    """licenses/README.md in English: the pack that goes to the client with the film."""
    root = os.path.abspath(root)
    brief = _brief(root)
    title = str(A.get("meta", {}).get("film") or brief.get("title") or os.path.basename(root)).strip()
    n = summary(A)
    L = [f"# {title}: licenses and sources", ""]
    film = os.path.join(root, "out", "final.mp4")
    if P is not None:
        L.append(f"Film: {round(P.duration, 1):g} s, {P.W}x{P.H}" + (" (`out/final.mp4`)." if os.path.exists(film) else ", final not rendered yet."))
    L += [f"Generated by `mv.py licenses` on {datetime.date.today().isoformat()} from `licenses/assets.yaml`. "
          "Edit the ledger, not this file, then run the command again.",
          "This folder lists every third-party element in the film and the proof that we may use it.", ""]
    if n["blocked"] or A["missing"]:
        L += [f"**Not cleared for publication.** {n['blocked']} element(s) blocked"
              + (f", {len(A['missing'])} file(s) with no record" if A["missing"] else "") + ".", ""]
    elif n["gap"]:
        L += [f"**Almost ready.** {n['gap']} element(s) still need a document or an approval (see To do).", ""]
    else:
        L += ["**Cleared.** Every element has a known source and license.", ""]

    L += ["## Status", "", "| Element | Source | License | Status |", "|---|---|---|---|"]
    for r in A["rows"]:
        it = r["item"]
        lic = str(it.get("license") or "unknown").lower()
        src_bits = [label(r)]
        if it.get("source"):
            src_bits.append(str(it["source"]))
        if _as_list(it.get("files")):
            src_bits.append("files: " + ", ".join(f"`{x}`" for x in _as_list(it.get("files"))))
        if it.get("obtained"):
            src_bits.append(f"obtained {it['obtained']}")
        lic_txt = LICENSES.get(lic, {}).get("name", "No license" if lic in ("", "unknown", "none", "?") else f"Not recognised ({lic})")
        if it.get("license_url"):
            lic_txt += f" ({it['license_url']})"
        terms = _as_list(it.get("terms"))
        if terms:
            lic_txt += ". Terms: " + ", ".join(f"`{t}`" for t in terms)
        if r["status"] == "ok":
            st = "[PASS]"
        elif r["status"] == "gap":
            st = "[GAP] " + "; ".join(r["gaps"])
        else:
            st = "[BLOCKED] " + "; ".join(r["blocked"])
        if it.get("note") and r["status"] != "blocked":
            st += f" Note: {it['note']}"
        L.append(f"| {_cell(str(it.get('kind') or ''))} | {_cell('. '.join(src_bits))} | {_cell(lic_txt)} | {_cell(st)} |")
    for a in A["auto"]:
        where = "project fonts/" if any(not os.path.isabs(f) for f in a["files"]) else "system font"
        L.append(f"| font | {_cell(a['family'])} ({where}) | {_cell(LICENSES[a['license']]['name'])}, "
                 f"declared in the font file | [PASS] |")
    for g in group_paths(A["missing"]):
        L.append(f"| ? | `{_cell(g)}` | not recorded | [BLOCKED] no record in licenses/assets.yaml |")
    L.append("")

    client_rows = [r for r in A["rows"] if str(r["item"].get("license", "")).lower() == "client" and r["status"] != "ok"]
    demo = _invented_copy(P)
    spoken = _voice_copy(root)
    copy_md = os.path.join(root, "licenses", "copy-for-approval.md")
    if demo or spoken:
        body = ("# Copy for the client's approval\n\n"
                f"Generated by `mv.py licenses` on {datetime.date.today().isoformat()}. Every line below was written by us, "
                "not taken from the brief. Numbers, prices, ratings and quotes are claims in the client's ad: "
                "the client approves them word for word.\n\n")
        if demo:
            body += "## On screen\n\n" + "\n".join(f"- [ ] «{t}»" for t in demo) + "\n\n"
        if spoken:
            body += "## Spoken by the voice-over\n\n" + "\n".join(f"- [ ] «{t}»" for t in spoken) + "\n"
        open(copy_md, "w", encoding="utf-8").write(body.rstrip() + "\n")

# ----------------------------------------------------------------------------- helpers

def _as_list(x):
    if x is None or x == "":
        return []
    return [str(v) for v in x] if isinstance(x, (list, tuple)) else [str(x)]


def _host(url):
    try:
        return (urlparse(url).hostname or "").lower()
    except Exception:
        return ""


def _rel(root, p):
    p = os.path.abspath(p)
    r = os.path.abspath(root)
    return os.path.relpath(p, r).replace(os.sep, "/") if p.startswith(r + os.sep) else p


def _kind(p):
    ext = os.path.splitext(p)[1].lower()
    for k, exts in KINDS.items():
        if ext in exts:
            return k
    return "file"


def _cell(x):
    return str(x).replace("|", "/").replace("\n", " ").strip()


def is_commercial(root, brief=None):
    """brief.yaml `use`: commercial (default for any real project) | internal (tests that never
    leave the team). No brief.yaml at all (engine tests, demos) counts as internal."""
    if brief is None:
        p = os.path.join(root, "brief.yaml")
        if not os.path.exists(p):
            return False
        import yaml
        brief = yaml.safe_load(open(p, encoding="utf-8")) or {}
    elif not brief and not os.path.exists(os.path.join(root, "brief.yaml")):
        return False
    return str(brief.get("use", "commercial")).strip().lower() != "internal"


def font_license(path, index=0):
    """(license key or None, family, license url) from the font's own name table, or from a
    license file next to it (OFL.txt and the like)."""
    fam, url, lic = os.path.basename(path), "", None
    try:
        from fontTools.ttLib import TTFont, TTCollection
        f = TTCollection(path, lazy=True).fonts[index] if path.lower().endswith((".ttc", ".otc")) else TTFont(path, lazy=True)
        nm = f["name"]
        fam = (nm.getDebugName(16) or nm.getDebugName(1) or fam).strip()
        url = (nm.getDebugName(14) or "").strip()
        low = " ".join(filter(None, (nm.getDebugName(i) for i in (0, 13, 14)))).lower()
    except Exception:
        low = ""
    if "open font license" in low or "sil.org/ofl" in low or "openfontlicense" in low:
        lic = "ofl"
    elif "apache license" in low or "apache.org/licenses" in low:
        lic = "apache"
    elif "ubuntu font licen" in low:
        lic = "ufl"
    elif "bitstream" in low and ("dejavu" in low or "vera" in low):
        lic = "bitstream"
    if lic is None:
        for side in glob.glob(os.path.join(os.path.dirname(path), "*")):
            b = os.path.basename(side).lower()
            if b.endswith(".txt") and ("ofl" in b or "license" in b or "licence" in b):
                try:
                    head = open(side, encoding="utf-8", errors="ignore").read(4000).lower()
                except Exception:
                    continue
                if "open font license" in head:
                    lic = "ofl"
                    break
    return lic, fam, url


def _walk_layers(P):
    seen = set()

    def rec(node):
        for c in getattr(node, "children", None) or []:
            if id(c) in seen:
                continue
            seen.add(id(c))
            yield c
            yield from rec(c)
            src = getattr(c, "src", None)
            if src is not None and hasattr(src, "render") and id(src) not in seen:
                seen.add(id(src))
                yield src
                yield from rec(src)
    for s in getattr(P, "scenes", []) or []:
        yield from rec(s)
    if getattr(P, "overlay", None) is not None:
        yield from rec(P.overlay)



"""Rights: where every external file in a film came from and why we may use it.

The ledger is <project>/licenses/assets.yaml (template: assets/templates/licenses.yaml).
`mv.py licenses <dir>` scans the project, adds a stub for every file the ledger does not cover,
copies the license snapshots and writes licenses/README.md: the pack that goes to the client
with the film. QA `rights` (qa.py) runs the same audit. On a commercial film (brief.yaml
`use: commercial`, the default) a file without a known license, or a blocked one, fails the final.

External files are: everything in assets/ and fonts/, every image or SVG the film draws (wherever
it lives), every font the text uses (project or system), the voice and the track in design.yaml
`sound`. Fonts whose own name table declares a free license (OFL, Apache, Ubuntu, Bitstream Vera /
DejaVu) pass without a ledger row. Sound made by the engine is code, not a file, and needs no row.

Reference material (refs/) never reaches the film: a file from refs/ on screen is blocked.
"""
